#!/usr/bin/env python3
"""Generate ledger.yaml from the pinned MCP tool snapshots, keeping statuses."""
import json
import pathlib
import re
import subprocess

MCP_VERSION = "v2.2.0"
LEDGER = pathlib.Path(__file__).with_name("ledger.yaml")
ROW = re.compile(r"^  ([a-z0-9_]+): (pending|partial|passing|out_of_scope)$")
OUT_OF_SCOPE = re.compile(r"copilot|github_support_docs_search")


def snapshot_tools():
    path = f"repos/github/github-mcp-server/contents/pkg/github/__toolsnaps__?ref={MCP_VERSION}"
    output = subprocess.run(["gh", "api", path], check=True, capture_output=True, text=True).stdout
    return sorted(e["name"][:-5] for e in json.loads(output) if e["name"].endswith(".snap"))


def existing_statuses():
    if not LEDGER.exists():
        return {}
    matches = (ROW.match(line) for line in LEDGER.read_text().splitlines())
    return {m.group(1): m.group(2) for m in matches if m}


def main():
    current = existing_statuses()
    lines = [
        "# Generated by conformance/gen_ledger.py. Edit statuses only.",
        f"mcp_server_version: {MCP_VERSION}",
        "tools:",
    ]
    for tool in snapshot_tools():
        default = "out_of_scope" if OUT_OF_SCOPE.search(tool) else "pending"
        lines.append(f"  {tool}: {current.get(tool, default)}")
    LEDGER.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
